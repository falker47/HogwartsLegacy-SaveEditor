"""Opt-in Windows/Oodle checks using generated data only. No personal saves are read."""
import argparse
import hashlib
import json
from pathlib import Path
import random
import sqlite3
import struct
import subprocess

from reproduce_converter_realloc import fstring, fixture_bytes


def database(size, seed, page_size=4096):
    with sqlite3.connect(':memory:') as db:
        db.execute(f'PRAGMA page_size={page_size}')
        db.execute('CREATE TABLE synthetic(value BLOB)')
        db.execute('INSERT INTO synthetic VALUES (?)', (random.Random(seed).randbytes(size),))
        db.commit()
        assert db.execute('PRAGMA integrity_check').fetchall() == [('ok',)]
        return db.serialize()


def wrap(images):
    header = (b'GVAS' + struct.pack('<iiHHHI', 2, 524, 4, 27, 2, 123)
              + fstring('synthetic') + struct.pack('<ii', 3, 0)
              + fstring('/Script/PersistentData.PersistentGameData'))
    output = bytearray(header)
    for name, image in zip(('RawDatabaseImage', 'RawExclusiveImage'), images):
        if name == 'RawExclusiveImage':
            # Deliberately opaque inter-image bytes, not regenerated by the converter.
            output += b'QA-BETWEEN\x00\xff\x80'
        payload = struct.pack('<i', len(image)) + image
        output += (fstring(name) + fstring('ArrayProperty') + struct.pack('<ii', len(payload), 0)
                   + fstring('ByteProperty') + b'\0' + payload)
    return bytes(output) + fstring('None') + b'QA-TAIL\x00\xff\x80' + bytes(range(256))


def cases():
    yield 'original-realloc-repro', fixture_bytes()
    # SQLite ignores unused page space. Fill it with deterministic noise so a
    # valid one-page DB can expand after Oodle framing (the HL-02D regression).
    images = []
    for page_size in (512, 4096):
        with sqlite3.connect(':memory:') as db:
            db.execute(f'PRAGMA page_size={page_size}')
            db.execute('PRAGMA user_version=1732584193')
            db.execute('PRAGMA application_id=19088743')
            raw = bytearray(db.serialize())
            assert len(raw) == page_size and raw[100] == 13 and raw[103:105] == b'\0\0'
            raw[108:] = random.Random(page_size).randbytes(page_size - 108)
            db.deserialize(bytes(raw))
            assert db.execute('PRAGMA integrity_check').fetchall() == [('ok',)]
            images.append(bytes(raw))
    yield 'expanding-valid-sqlite-pages', wrap(images)
    for size in (0, 100, 36000, 250000, 262144, 524288, 1048576, 4194304):
        yield f'entropy-{size}-db1-db2', wrap((database(size, size + 1), database(size // 2, size + 2)))
    yield 'db2-absent', wrap((database(524288, 101),))


def validate(converter, expected_sha256, output):
    converter = Path(converter).resolve(strict=True)
    if hashlib.sha256(converter.read_bytes()).hexdigest() != expected_sha256.lower():
        raise ValueError('Converter SHA256 mismatch')
    runtime = converter.with_name('oo2core_9_win64.dll')
    runtime_hash = hashlib.sha256(runtime.read_bytes()).hexdigest()
    output = Path(output).resolve()
    output.mkdir(parents=True, exist_ok=False)
    report = {'converter_sha256': expected_sha256.lower(), 'oodle_sha256': runtime_hash,
              'cycles_per_case': 5, 'cases': []}
    for label, original in cases():
        folder = output / label
        folder.mkdir()
        source = folder / 'source.decomp'
        source.write_bytes(original)
        current = source
        for cycle in range(5):
            packed = folder / f'{cycle}.sav'
            unpacked = folder / f'{cycle}.decomp'
            for mode, src, dst in (('-c', current, packed), ('-d', packed, unpacked)):
                run = subprocess.run([str(converter), mode, str(src), str(dst)], cwd=converter.parent,
                                     stdin=subprocess.DEVNULL, capture_output=True, timeout=60)
                if run.returncode != 0 or not dst.is_file():
                    raise RuntimeError(f'{label} cycle {cycle} {mode}: exit {run.returncode}')
            assert unpacked.read_bytes() == original, (label, cycle, 'round-trip differs')
            assert source.read_bytes() == original, (label, 'source changed')
            current = unpacked
        report['cases'].append({'case': label, 'input_bytes': len(original),
                                'compressed_bytes': packed.stat().st_size, 'exact': True})
        if label == 'expanding-valid-sqlite-pages':
            assert packed.stat().st_size > len(original), 'Fixture must exercise output expansion'
    (output / 'result.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
    return report


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--converter', required=True, type=Path)
    parser.add_argument('--expected-sha256', required=True)
    parser.add_argument('--out-dir', required=True, type=Path)
    args = parser.parse_args()
    print(json.dumps(validate(args.converter, args.expected_sha256, args.out_dir), indent=2))
